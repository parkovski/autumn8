#!/usr/bin/env node

const fs = require('fs');

let inp = process.argv[2];
let out = process.argv[3];

function usage() {
  console.error('usage: node mimetypes.js <mime.types> [mime.types.cpp | -]');
  console.error('converts nginx\'s mime.types file to C++');
  process.exit(1);
}

if (!inp) {
  usage();
}
if (!out) {
  out = require('path').join(__dirname, '..', 'src/util/mime.types.cpp');
}

try {
  inp = fs.readFileSync(inp, 'utf8');
} catch (e) {
  console.error(`couldn't read from ${inp}`);
  process.exit(1);
}

inp = inp
  .replace(/^\s*types\s*\{([^]+)\}\s*$/m, '$1')
  .split(';')
  .map(line => {
    // looks like "text/html    html"
    let matches = line.match(/\s*(\S+)\s+(.+)/);
    if (!matches) {
      return;
    }
    return matches[2].trim().split(/\s+/)
      .reduce((a, c) => {
        if (~c.indexOf('.')) {
          a.names.push(c);
        } else {
          a.exts.push(c);
        }
        return a;
      }, { mime: matches[1], exts: [], names: [] });
  })
  .filter(x => x);

const o =
`// *** Autogenerated by mimetypes.js ***
#include "a8/util/mime.types.h"

std::unordered_map<const char *, const char *>
a8::getMimeTypeMap(bool names, bool exts) {
  std::unordered_map<const char *, const char *> m;

  if (names) {
${inp
  .flatMap(entry =>
    entry.names.map(n => `    m.emplace("${n}", "${entry.mime}");`))
  .join('\n')}
  }

  if (exts) {
${inp
  .flatMap(entry =>
    entry.exts.map(e => `    m.emplace("${e}", "${entry.mime}");`))
  .join('\n')}
  }

  return m;
}
`;

if (out === '-') {
  console.log(o);
} else {
  fs.writeFileSync(out, o, 'utf8');
}